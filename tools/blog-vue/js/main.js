/* ============================================================================
   main.js —— 挂载入口（就这几行）
   ============================================================================
   【为什么要单独一个文件】
     app.js 现在只"定义应用"，不"挂载应用"。
     挂载这件事本身带副作用（会去操作真实 DOM、发真实请求），
     所以把它单独放这里，好处是：

       · 页面加载：index.html 引 main.js → 挂到 #app → 真发请求
       · 跑测试：  测试引 app.js 的 createBlogApp() → 挂到 jsdom 的假页面
                   → 用假的 fetch 喂数据（不联网）

     这就是"把副作用隔离到入口"的写法，也是 Vue/React 项目里
     main.js 与 App.vue 分开的常见原因。
   ========================================================================== */

// ⚠ 相对路径而不是裸名 'vue'：浏览器和 node 都能直接解析（理由见 app.js 顶部注释）
import { createApp } from './vendor/vue.esm-browser.prod.js';
import { createBlogApp } from './app.js';

// 挂到页面上 id="app" 的元素
createBlogApp({ createApp }).mount('#app');
